import { test, expect } from '@playwright/test';
import path from 'node:path';
test('admin sign-in, metrics, browser fixture job, persisted schedules, explorer, changes and reviews', async ({ page }, info) => {
  test.skip(!process.env.MYGOVGUIDE_E2E_ADMIN_PASSWORD, 'Use npm run test:e2e for isolated admin bootstrap');
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/admin');
  await expect(page.getByRole('heading', { name: 'Welcome to operations' })).toBeVisible();
  await page.getByLabel('Username').fill('admin@example.test');
  await page.getByLabel('Password', { exact: true }).fill(process.env.MYGOVGUIDE_E2E_ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Sign in securely' }).click();
  await expect(page.getByRole('heading', { name: 'A clear view of the pipeline' })).toBeVisible();
  await expect(page.locator('.ad-metrics article').filter({ hasText: 'Schemes' }).locator('strong')).toHaveText('25');
  await page.screenshot({ path: path.join('reports', `admin-overview-${info.project.name}.png`), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Run collection', exact: true }).first().click();
  await page.getByLabel('Configured source').selectOption('fixture-api');
  await page.getByRole('button', { name: 'Run collection', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Execution details' });
  await expect(dialog).toContainText('SUCCEEDED', { timeout: 20000 });
  await expect(dialog).toContainText('FIXTURE'); await expect(dialog).toContainText('MANUAL');
  await page.getByRole('button', { name: 'Close details' }).click();
  await page.getByRole('link', { name: 'Schedules', exact: true }).click();
  const name = `Browser fixture ${info.project.name}`;
  await page.getByLabel('Schedule name').fill(name);
  await page.getByRole('button', { name: 'Validate schedule' }).click(); await expect(page.getByRole('status')).toContainText('Valid');
  await page.getByRole('button', { name: 'Create schedule' }).click();
  const toggle = page.getByRole('switch', { name: `Automatic collection for ${name}` });
  await expect(toggle).toHaveAttribute('aria-checked', 'false'); await toggle.click(); await expect(toggle).toHaveAttribute('aria-checked', 'true');
  await page.reload(); await expect(toggle).toHaveAttribute('aria-checked', 'true'); await toggle.click(); await expect(toggle).toHaveAttribute('aria-checked', 'false');
  await page.getByRole('link', { name: 'Execution history' }).click(); await expect(page.locator('table')).toContainText('SUCCEEDED');
  await page.getByRole('link', { name: 'Data explorer' }).click(); await page.getByLabel('Record type').selectOption('ScamAlert');
  await expect(page.locator('table')).toContainText('AWARENESS_TOPIC'); await expect(page.locator('table')).toContainText('Not supplied');
  await page.locator('.ad-text-button').first().click(); await expect(page.getByRole('dialog')).toContainText('primaryOfficialUrl'); await page.getByRole('button', { name: 'Close details' }).click();
  await page.getByRole('link', { name: 'Change Radar' }).click(); await page.getByRole('button', { name: 'Compare versions' }).first().click();
  await expect(page.getByRole('dialog')).toContainText('Previous'); await expect(page.getByRole('dialog')).toContainText('Observed'); await page.getByRole('button', { name: 'Close details' }).click();
  await page.getByRole('link', { name: 'Review queue' }).click(); await page.getByRole('button', { name: 'Review', exact: true }).first().click();
  await page.getByLabel('Supporting evidence').fill('Synthetic browser test: keep this observation internal pending source review.');
  await page.getByRole('button', { name: 'Record decision' }).click(); await expect(page.getByRole('status').first()).toContainText('Review recorded');
  await page.getByRole('link', { name: 'System', exact: true }).click(); await expect(page.locator('.ad-health')).toContainText('false');
  await page.getByRole('button', { name: 'Sign out' }).click(); await expect(page.getByRole('heading', { name: 'Welcome to operations' })).toBeVisible();
  expect(errors).toEqual([]);
});
